CREATE FUNCTION yarenler_alan_slug_ata() RETURNS integer
    LANGUAGE plpgsql AS $$
DECLARE r record; aday text; uye_slug text; sayi integer := 0;
BEGIN
    -- Kanonik satır değiştiyse adres kavramla birlikte taşınır.
    FOR r IN
        SELECT k.id,
               (SELECT m.id FROM research_area m WHERE m.kanonik_id = k.id AND m.slug IS NOT NULL ORDER BY m.olusturma, m.id LIMIT 1) AS uye
          FROM research_area k
         WHERE k.kanonik_id IS NULL AND k.slug IS NULL
    LOOP
        IF r.uye IS NOT NULL THEN
            SELECT slug INTO uye_slug FROM research_area WHERE id = r.uye;
            UPDATE research_area SET slug = NULL WHERE id = r.uye;
            UPDATE research_area SET slug = uye_slug WHERE id = r.id;
            sayi := sayi + 1;
        END IF;
    END LOOP;
    -- Yeni adresler: en çok kişiye bağlı alan sade biçimi alır, çakışan diğerine kısa kimlik eklenir.
    FOR r IN
        SELECT k.id, coalesce(nullif(yarenler_slug(yarenler_alan_temiz(coalesce(k.ad_tr, k.ad_en))), ''), 'alan') AS taban
          FROM research_area k
         WHERE k.kanonik_id IS NULL AND k.slug IS NULL
         ORDER BY (SELECT count(*) FROM person_research_area pa JOIN research_area s ON s.id = pa.area_id
                    WHERE coalesce(s.kanonik_id, s.id) = k.id) DESC, k.id
    LOOP
        aday := r.taban;
        IF EXISTS (SELECT 1 FROM research_area WHERE slug = aday) THEN
            aday := r.taban || '-' || substr(md5(r.id::text), 1, 6);
        END IF;
        IF EXISTS (SELECT 1 FROM research_area WHERE slug = aday) THEN
            aday := r.taban || '-' || substr(md5(r.id::text), 1, 12);
        END IF;
        UPDATE research_area SET slug = aday WHERE id = r.id;
        sayi := sayi + 1;
    END LOOP;
    RETURN sayi;
END $$;

-- Kanonikleştirme artık İngilizce adları ve adresleri de günceller (içe aktarma sonunda çağrılır).
CREATE OR REPLACE FUNCTION yarenler_alan_kanoniklestir() RETURNS integer
    LANGUAGE plpgsql AS $$
DECLARE degisen integer;
BEGIN
    WITH aday AS (
        SELECT a.id,
               yarenler_alan_anahtar(coalesce(a.ad_tr, a.ad_en)) AS anahtar,
               (SELECT count(*) FROM person_research_area pa WHERE pa.area_id = a.id) AS kisi,
               array_position(ARRAY['avesis','scopus','wos','openalex','yarenler']::alan_semasi[], a.sema) AS sira
          FROM research_area a
    ), secim AS (
        SELECT id, anahtar,
               first_value(id) OVER (PARTITION BY anahtar ORDER BY kisi DESC, sira, id) AS kanonik
          FROM aday WHERE anahtar IS NOT NULL
    ), guncel AS (
        UPDATE research_area a
           SET kanonik_id = CASE WHEN s.kanonik = a.id THEN NULL ELSE s.kanonik END,
               guncelleme = now()
          FROM secim s
         WHERE s.id = a.id AND a.kanonik_id IS DISTINCT FROM CASE WHEN s.kanonik = a.id THEN NULL ELSE s.kanonik END
        RETURNING a.id
    )
    SELECT count(*) INTO degisen FROM guncel;

    INSERT INTO research_area_synonym (area_id, ad, dil, normalize_ad, kaynak)
    SELECT DISTINCT ON (a.kanonik_id, yarenler_katla(n.ad)) a.kanonik_id, n.ad, n.dil, yarenler_katla(n.ad), 'sema'
      FROM research_area a
      CROSS JOIN LATERAL (VALUES (a.ad_tr, 'tr'), (a.ad_en, 'en')) AS n(ad, dil)
     WHERE a.kanonik_id IS NOT NULL AND n.ad IS NOT NULL
    ON CONFLICT (normalize_ad, area_id) DO NOTHING;

    PERFORM yarenler_alan_ingilizce_doldur();
    PERFORM yarenler_alan_slug_ata();
    RETURN degisen;
END $$;

