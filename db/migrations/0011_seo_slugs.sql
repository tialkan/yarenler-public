-- Paket 2 (SEO): kalıcı ve okunur adresler, İngilizce alan adları, duyuru kısa kimliği.
--
-- 1. Birim adresi /tr/birim/{slug}: ad tabanlı, genel olarak benzersiz; çakışmada -2, -3.
--    Eski "birim-<özet>" adresi unit.eski_slug içinde kalır ve 308 ile yenisine yönlenir.
-- 2. Alan adresi /tr/alan/{slug}: yalnız kanonik satırda; çakışmada kısa kimlik eki.
--    Kanonik satır değişirse slug kavramla birlikte yeni kanonik satıra taşınır.
--    Eski UUID'li adres ve birleşmiş alan adresi uygulamada kimlikten kanonik slug'a 308 olur.
-- 3. İngilizce alan adları: AVESİS araştırma sayfasındaki iki dilli sınıflama sözlüğünden
--    (Primary/Secondary). Çeviri yapılmaz. Aynı anahtar birden çok İngilizce ada gidiyorsa ad boş kalır.
-- 4. Duyuru kısa kimliği: /tr/duyuru/{kisa_kimlik}-{slug}.

-- Türkçe karakterleri doğru dönüştüren adres parçası (ı→i, ş→s, ğ→g, ç→c, ö→o, ü→u).
-- Uygulamadaki karşılığı ve testi: apps/web/src/server/slug.ts.
CREATE FUNCTION yarenler_slug(metin text, azami integer DEFAULT 80) RETURNS text
    LANGUAGE plpgsql IMMUTABLE STRICT PARALLEL SAFE AS $$
DECLARE s text;
BEGIN
    s := btrim(regexp_replace(yarenler_katla(metin), '[^a-z0-9]+', '-', 'g'), '-');
    IF length(s) > azami THEN
        s := left(s, azami + 1);
        IF position('-' IN s) > 0 THEN
            s := regexp_replace(s, '-[^-]*$', '');
        ELSE
            s := left(s, azami);
        END IF;
        s := btrim(s, '-');
    END IF;
    RETURN s;
END $$;

