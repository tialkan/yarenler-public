-- İlk boş aday: "ad", "ad-2", "ad-3"... Eski adreslerle de çakışmaz.
CREATE FUNCTION yarenler_birim_slug_yeni(ad text, haric uuid DEFAULT NULL) RETURNS text
    LANGUAGE plpgsql AS $$
DECLARE taban text := coalesce(nullif(yarenler_slug(ad), ''), 'birim'); aday text; n integer := 1;
BEGIN
    aday := taban;
    WHILE EXISTS (SELECT 1 FROM unit WHERE (slug = aday OR eski_slug = aday) AND id IS DISTINCT FROM haric) LOOP
        n := n + 1;
        aday := taban || '-' || n;
    END LOOP;
    RETURN aday;
END $$;

-- Sade biçim önce fakültelere, sonra bölümlere ve kişi sayısı yüksek birimlere verilir.
DO $$
DECLARE r record;
BEGIN
    FOR r IN
        SELECT u.id, u.ad_tr FROM unit u
         ORDER BY array_position(ARRAY['fakulte','enstitu','yuksekokul','bolum','anabilim_dali','diger'], u.tur),
                  (SELECT count(*) FROM person p WHERE p.unit_id = u.id) DESC, u.olusturma, u.id
    LOOP
        UPDATE unit SET slug = yarenler_birim_slug_yeni(r.ad_tr, r.id) WHERE id = r.id;
    END LOOP;
END $$;
CREATE UNIQUE INDEX unit_slug_key ON unit (slug);

