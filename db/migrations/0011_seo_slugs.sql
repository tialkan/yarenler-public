-- research_area.ad_en boşsa sözlükten doldurur; kanonik satır, kendi adı yoksa birleşen satırın adını alır.
CREATE FUNCTION yarenler_alan_ingilizce_doldur() RETURNS integer
    LANGUAGE plpgsql AS $$
DECLARE dolan integer; miras integer;
BEGIN
    UPDATE research_area a
       SET ad_en = s.ad_en, ad_en_kaynak = 'avesis_sozluk', guncelleme = now()
      FROM alan_ad_sozlugu s
     WHERE a.ad_en IS NULL AND a.ad_tr IS NOT NULL
       AND s.sema = a.sema AND s.anahtar = yarenler_alan_anahtar(a.ad_tr);
    GET DIAGNOSTICS dolan = ROW_COUNT;
    UPDATE research_area k
       SET ad_en = m.ad_en, ad_en_kaynak = m.ad_en_kaynak, guncelleme = now()
      FROM (SELECT DISTINCT ON (kanonik_id) kanonik_id, ad_en, ad_en_kaynak
              FROM research_area
             WHERE kanonik_id IS NOT NULL AND ad_en IS NOT NULL
             ORDER BY kanonik_id, array_position(ARRAY['avesis','scopus','wos','openalex','yarenler']::alan_semasi[], sema), id) m
     WHERE k.id = m.kanonik_id AND k.kanonik_id IS NULL AND k.ad_en IS NULL;
    GET DIAGNOSTICS miras = ROW_COUNT;
    RETURN dolan + miras;
END $$;

